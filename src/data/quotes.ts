export function getQuoteIndex(date = new Date(), total = quotes.length): number {
  if (total <= 0) {
    return 0;
  }

  const dayStart = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  return Math.abs(Math.floor(dayStart.getTime() / 86_400_000)) % total;
}

export function getDailyQuote(date = new Date()): Quote {
  return quotes[getQuoteIndex(date)] ?? quotes[0];
}
